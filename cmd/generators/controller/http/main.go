// Package generators/controller/http generates http controller from .json file with their description.
// Config file is described by httpStruct for main http.go file and endpointStruct for endpoint files.
// Execution: go run <<path to generators/controller/http/main.go>> <<path to .json configuration>> <<path to controller pakage>>.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	stringoperations "messenger/pkg/string_operations"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"golang.org/x/tools/imports"
)

const httpFileTemplate = `// Code generated by generators/controller/http. DO NOT EDIT.
// Package http implements controller by HTTP handler.
	package http

	import ()

	// HTTPControllerInterfece defines all handler methods.
	type HTTPControllerInterface interface {
		{{.HTTPControllerMethods}}
	}

	// HTTPController is a default implementation of HTTPControllerInterface.
	type HTTPController struct {
		r  *chi.Mux
		v  *validator.Validate
		uc usecase.UsecaseInterface
	}

	// NewHTTPController initializes HTTPController and returns pointer on it.
	func NewHTTPController(uc *usecase.Usecase) *HTTPController {
		return &HTTPController{r: chi.NewRouter(), v: validator.New(validator.WithRequiredStructEnabled()), uc: uc}
	}

	// DefineEndpoint is a method for definding all endpoints in chi router.
	func (c *HTTPController) DefindEndpoints() {
		{{.EndpointDifinitions}}
	}

	// UseMiddleware adds new middleware usage to the controller.
	func (c *HTTPController) UseMiddleware(f func(http.Handler) http.Handler) { c.r.Use(f) }

	// ListenAndServe starts listening on the received address.
	func (c *HTTPController) ListenAndServe(addr string) { http.ListenAndServe(addr, c.r) }
`

const endpointFileTemplate = `// Code generated by generators/controller/http. DO NOT EDIT.
package http

import ()

// {{.LowerCasedName}}Request defines signup request structure
{{.RequestStruct}}

// {{.UpperCasedName}} implements the {{.UnderscoreSplittedName}} endpoint on the controller layer.
// The method parses request structure and calls usecase.Usecase.{{.UpperCasedName}}().
func (c *HTTPController) {{.UpperCasedName}}(w http.ResponseWriter, r *http.Request) {
	{{.IdentChceck}}
	{{.RequestGetting}}
	{{.ContextValuseGetting}}
	{{.URLParamsGetting}}
	var input dto.{{.UpperCasedName}}Input = dto.{{.UpperCasedName}}Input{{.InputFieldPairs}}

	if err := c.v.Struct(input); err != nil {
		http.Error(w, fmt.Sprintf("validation error: %s", err.Error()), http.StatusBadRequest)
		return
	}

	output, err := c.uc.{{.UpperCasedName}}(input)
	if err != nil {
		{{.ErrorsParsing}}
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	w.Header().Set("Content-Type", "application/json")

	w.WriteHeader(http.StatusOK)

	if err := json.NewEncoder(w).Encode(output); err != nil {
		http.Error(w, fmt.Sprintf("encoding error: %s", err.Error()), http.StatusInternalServerError)
		return
	}
}
}`

type configStruct struct {
	HTTPStruct      httpStruct       `json:"httpStruct"`
	EndpointStructs []endpointStruct `json:"endpointStructs"`
}

// handlerStruct defines the configuration file structure
type httpStruct struct {
	HTTPControllerMethods []string             `json:"httpControllerMethods"`
	EndpointDifinitions   []endpointDefinition `json:"endpointDifinitions"`
}

type endpointDefinition struct {
	Method   string `json:"method"`
	Endpoint string `json:"endpoint"`
	Name     string `json:"name"`
}

// handlerStruct defines the configuration file structure
type endpointStruct struct {
	Name          string       `json:"name"`
	RequestFields []string     `json:"requestFields"`
	IdentCheck    bool         `json:"identCheck"`
	ContextValues []string     `json:"contextValues"`
	URLParams     []string     `json:"urlParams"`
	ErrorsToCheck []errToCheck `json:"errorsToCheck"`
}

type errToCheck struct {
	Name            string `json:"name"`
	HTTPDescription string `json:"httpDescription"`
}

const httpFileName = "http.go"

func generateHTTPFile(http httpStruct, t *template.Template, packagePath string) {
	var httpControllerMethodsStr string
	var endpointDifinitionsStr string

	for _, method := range http.HTTPControllerMethods {
		httpControllerMethodsStr += fmt.Sprintf("%s(w http.ResponseWriter, r *http.Request)\n", stringoperations.SpaceSplittedToUpperCamelCase(method))
	}
	for _, difinition := range http.EndpointDifinitions {
		endpointDifinitionsStr += fmt.Sprintf(`c.r.%s("%s", c.%s)`, stringoperations.SpaceSplittedToUpperCamelCase(difinition.Method), stringoperations.SpaceSplittedToUpperCamelCase(difinition.Endpoint), stringoperations.SpaceSplittedToUpperCamelCase(difinition.Name))
	}

	filePath := filepath.Join(packagePath, httpFileName)

	var buf bytes.Buffer
	err := t.Execute(&buf, map[string]interface{}{
		"HTTPControllerMethods": httpControllerMethodsStr,
		"EndpointDifinitions":   endpointDifinitionsStr,
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "http file generation: template executing error: %s", err.Error())
		return
	}

	formatted, err := imports.Process(httpFileName, buf.Bytes(), nil)
	if err != nil {
		fmt.Fprintf(os.Stderr, "http file generation: formatting error: %s", err.Error())
		return
	}

	err = os.WriteFile(filePath, formatted, 0644)
	if err != nil {
		fmt.Fprintf(os.Stderr, "http file generation: file writing error: %s", err.Error())
		return
	}
}

func generateEndpointFiles(endpoints []endpointStruct, t *template.Template, packagePath string) {
	for _, endpoint := range endpoints {
		var requestStruct string
		var identCheck string
		var requestGetting string
		var contextValuesGetting string
		var urlParamsGetting string
		var errorsParsingStr string
		inputFieldPairs := "{"
		lowerCasedName := stringoperations.SpaceSplittedToLowerCamelCase(endpoint.Name)
		upperCasedName := stringoperations.SpaceSplittedToUpperCamelCase(endpoint.Name)
		underscoreSplittedName := stringoperations.SpaceSplittedToUnderscoreSplitted(endpoint.Name)

		if endpoint.IdentCheck {
			identCheck = `	isIdentified := r.Context().Value("is_identified").(bool)
				if !isIdentified {
					http.Error(w, "not identified", http.StatusUnauthorized)
					return
				}
				`
		}

		if len(endpoint.RequestFields) != 0 {
			requestStruct = fmt.Sprintf("type %sRequest struct {", stringoperations.SpaceSplittedToLowerCamelCase(endpoint.Name))

			for _, field := range endpoint.RequestFields {
				requestStruct += field

				parts := strings.Split(field, " ")

				if len(parts) < 2 {
					fmt.Fprint(os.Stderr, "invalid struct filed")
					return
				}

				inputFieldPairs += fmt.Sprintf("%s: req.%s, ", stringoperations.SpaceSplittedToUpperCamelCase(parts[1]), stringoperations.SpaceSplittedToLowerCamelCase(parts[1]))
			}

			requestGetting = `	var req createChatRequest

					err := json.NewDecoder(r.Body).Decode(&req)
					if err != nil {
						http.Error(w, fmt.Sprintf("decoding error: %s", err.Error()), http.StatusBadRequest)
						return
					}
					defer r.Body.Close()
					`

			inputFieldPairs += "req: req, "
		}

		for _, contextValue := range endpoint.ContextValues {
			contextValuesGetting += fmt.Sprintf(`%s := r.Context().Value("%s").(uint)`, stringoperations.SpaceSplittedToLowerCamelCase(contextValue), stringoperations.SpaceSplittedToUnderscoreSplitted(contextValue))

			inputFieldPairs += fmt.Sprintf("%s: %s, ", stringoperations.SpaceSplittedToUpperCamelCase(contextValue), stringoperations.SpaceSplittedToLowerCamelCase(contextValue))
		}

		for _, urlParam := range endpoint.URLParams {
			urlParamsGetting += fmt.Sprintf(`%s, err := strconv.Atoi(chi.URLParam(r, "%s"))
				if err != nil {
					http.Error(w, fmt.Sprintf("invalid id: %s", err.Error()), http.StatusBadRequest)
					return
				}`, stringoperations.SpaceSplittedToLowerCamelCase(urlParam), stringoperations.SpaceSplittedToLowerCamelCase(urlParam), "%"+"s")

			inputFieldPairs += fmt.Sprintf("%s: %s, ", stringoperations.SpaceSplittedToUpperCamelCase(urlParam), stringoperations.SpaceSplittedToLowerCamelCase(urlParam))
		}

		for _, err := range endpoint.ErrorsToCheck {
			errorsParsingStr += fmt.Sprintf(`		if errors.Is(err, domain.%s) {
				http.Error(w, "%s", http.StatusForbidden)
				return
				}`, stringoperations.SpaceSplittedToUpperCamelCase(err.Name), err.HTTPDescription)
		}

		inputFieldPairs += "}"

		fileName := stringoperations.SpaceSplittedToUnderscoreSplitted(endpoint.Name) + ".go"

		filePath := filepath.Join(packagePath, fileName)

		var buf bytes.Buffer
		err := t.Execute(&buf, map[string]interface{}{
			"LowerCasedName":         lowerCasedName,
			"UpperCasedName":         upperCasedName,
			"UnderscoreSplittedName": underscoreSplittedName,
			"RequestStruct":          requestStruct,
			"IdentCheck":             identCheck,
			"RequestGetting":         requestGetting,
			"ContextValuesGetting":   contextValuesGetting,
			"URLParamsGetting":       urlParamsGetting,
			"InputFilePairs":         inputFieldPairs,
			"ErrorParsing":           errorsParsingStr,
		})
		if err != nil {
			fmt.Fprintf(os.Stderr, "http file generation: template executing error: %s", err.Error())
			return
		}

		formatted, err := imports.Process(fileName, buf.Bytes(), nil)
		if err != nil {
			fmt.Fprintf(os.Stderr, "http file generation: formatting error: %s", err.Error())
			return
		}

		err = os.WriteFile(filePath, formatted, 0644)
		if err != nil {
			fmt.Fprintf(os.Stderr, "http file generation: file writing error: %s", err.Error())
			return
		}
	}
}

func main() {
	args := os.Args
	if len(args) != 3 {
		panic(fmt.Errorf("unexpected arguments count (%d)", len(args)))
	}

	configPath := args[1]
	packagePath := args[2]

	configData, err := os.ReadFile(configPath)
	if err != nil {
		panic(fmt.Errorf("config file reading file: %w", err))
	}

	var config configStruct

	if err := json.Unmarshal(configData, &config); err != nil {
		panic(fmt.Errorf("config file unmarshaling file: %w", err))
	}

	generateHTTPFile(config.HTTPStruct, template.Must(template.New("genHTTP").Parse(httpFileTemplate)), packagePath)
	generateEndpointFiles(config.EndpointStructs, template.Must(template.New("genEndpoint").Parse(endpointFileTemplate)), packagePath)
}
