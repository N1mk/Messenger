// Package generators/dto generates dto structures from .json file with their description.
// Config file is described by endpointStruct structure.
// Execution: go run <<path to generators/dto/main.go>> <<path to .json configuration>> <<path to dto pakage>>.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	stringoperations "messenger/pkg/string_operations"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"golang.org/x/tools/imports"
)

const fileTemplate = `// Code generated by generators/dto. DO NOT EDIT.
package dto

import()

// {{.StructName}}Input is a data transfer structure defining contract between controller and usecase
type {{.StructName}}Input struct {
	{{.InputFields}}
}

// {{.StructName}}Output is a data transfer structure defining contract between controller and usecase
type {{.StructName}}Output struct {
	{{.OutputFields}}
}`

// endpointStruct defines the configuration file structure
type endpointStruct struct {
	Name         string   `json:"name"`
	InputFields  []string `json:"inputFields"`
	OutputFields []string `json:"outputFields"`
}

func main() {
	args := os.Args
	if len(args) != 3 {
		panic(fmt.Errorf("unexpected arguments count (%d)", len(args)))
	}

	configPath := args[1]
	packagePath := args[2]

	configData, err := os.ReadFile(configPath)
	if err != nil {
		panic(fmt.Errorf("config file reading file: %w", err))
	}

	var endpoints []endpointStruct

	if err := json.Unmarshal(configData, &endpoints); err != nil {
		panic(fmt.Errorf("config file unmarshaling file: %w", err))
	}

	t := template.Must(template.New("gen").Parse(fileTemplate))

	for _, endpoint := range endpoints {
		// Parsing endpoint name

		fileName := stringoperations.SpaceSplittedToUnderscoreSplitted(endpoint.Name) + ".go"
		structName := stringoperations.SpaceSplittedToUpperCamelCase(endpoint.Name)

		// Generating file

		filePath := filepath.Join(packagePath, fileName)

		var buf bytes.Buffer
		err := t.Execute(&buf, map[string]interface{}{
			"StructName":   structName,
			"InputFields":  strings.Join(endpoint.InputFields, "\n"),
			"OutputFields": strings.Join(endpoint.OutputFields, "\n"),
		})
		if err != nil {
			fmt.Fprintf(os.Stderr, "template executing error: %s", err.Error())
			continue
		}

		formatted, err := imports.Process(fileName, buf.Bytes(), nil)
		if err != nil {
			fmt.Fprintf(os.Stderr, "formatting error: %s", err.Error())
			continue
		}

		err = os.WriteFile(filePath, formatted, 0644)
		if err != nil {
			fmt.Fprintf(os.Stderr, "file writing error: %s", err.Error())
			continue
		}
	}
}
